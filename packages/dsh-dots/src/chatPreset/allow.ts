/**
 * 「云端对话模式」的**纯对话工具白名单**——运行期反算 deny 时唯一允许留下的名字。
 *
 * ## 为什么只有两个
 *
 * 准入判据是 Lead 拍板的这一条（逐字，评审时不要改写成别的说法）：
 *
 * > 判据是「**能不能读写本机文件 / 执行本机命令 / 读取本机环境**」，不是"有没有副作用"。
 *
 * 按这条判据过一遍，绝大多数工具都过不去：`read`/`write`/`edit`/`glob`/`grep` 读写本机文件，
 * `bash`/`pwsh`/`job_*` 执行本机命令（后台任务里同样能跑命令、读输出），`timeline_*` 读写本机
 * 日程库并 push，`bcdp_*` 能接管真实浏览器、下载落盘、上传本机文件，`codex_image_generate`
 * 写附件，`dsh_dots` 读本机会话状态——它们**不是"有副作用所以禁"，而是"碰本机"所以禁**。
 *
 * 反过来，"有副作用"本身不构成禁令：`todo_write` 会改变状态（写计划），但它只写**会话内**
 * 的计划，而会话本来就要上传 `chats/`（P1 已定的出口契约），既不碰本机文件系统、也不执行
 * 本机命令、更不读本机环境；`ask_user_question` 只向用户提问，连持久化都没有。所以两者留下。
 *
 * ## 与 deny 的关系（别反过来读）
 *
 * `deny = 当前已注册的全部工具 − CHAT_ALLOW_TOOLS`，在**运行期**由
 * `src/chatPreset/isolate.ts` 的 `computeDeny` 反算。本文件是**唯一的白名单输入**：
 * 想放开一个工具 → 加进这里并补一条 `ALLOW_RATIONALE`；想收紧 → 从 deny 侧什么也不用做
 * （新注册的工具默认就落在 deny 里）。**不要**再维护任何"静态 deny 名单"：插件在运行期
 * 注册工具，数量与名字都不稳定，写死的黑名单必然要么漏、要么把未注册的名字带进
 * `ctx.tools.restrict()` 导致抛错（`docs/RESEARCH-chat-preset.md`「结论补充」§5）。
 */

